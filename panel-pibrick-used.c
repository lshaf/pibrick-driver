static int visionox_vtdr6110_probe(struct mipi_dsi_device *dsi)
{
	struct device *dev = &dsi->dev;
	struct visionox_vtdr6110 *ctx;
	int ret;

	// New Linux Kernel Allocation
	// ctx = devm_drm_panel_alloc(dev, struct visionox_vtdr6110, panel,
	// 			   &visionox_vtdr6110_panel_funcs,
	// 			   DRM_MODE_CONNECTOR_DSI);
	// if (IS_ERR(ctx))
	// 	return PTR_ERR(ctx);

	ctx = devm_kzalloc(dev, sizeof(*ctx), GFP_KERNEL);
	if (!ctx)
		return -ENOMEM;

	ret = devm_regulator_bulk_get_const(&dsi->dev,
					    ARRAY_SIZE(visionox_vtdr6110_supplies),
					    visionox_vtdr6110_supplies,
					    &ctx->supplies);
	if (ret < 0)
		return ret;

	ctx->reset_gpio = devm_gpiod_get(dev, "reset", GPIOD_OUT_LOW);
	if (IS_ERR(ctx->reset_gpio))
		return dev_err_probe(dev, PTR_ERR(ctx->reset_gpio),
				     "Failed to get reset-gpios\n");

	drm_panel_init(&ctx->panel, &dsi->dev, &visionox_vtdr6110_panel_funcs,
		       DRM_MODE_CONNECTOR_DSI);

	ctx->dsi = dsi;
	mipi_dsi_set_drvdata(dsi, ctx);

	/* DSI Configuration */
	dsi->lanes = 4;
	dsi->format = MIPI_DSI_FMT_RGB888;
	dsi->mode_flags = MIPI_DSI_MODE_VIDEO | MIPI_DSI_MODE_NO_EOT_PACKET |
			  MIPI_DSI_CLOCK_NON_CONTINUOUS;
	// dsi->mode_flags =  MIPI_DSI_MODE_VIDEO | MIPI_DSI_MODE_NO_EOT_PACKET |
	// 		  MIPI_DSI_CLOCK_NON_CONTINUOUS;
	
	// dsi->mode_flags =  MIPI_DSI_MODE_VIDEO | MIPI_DSI_MODE_VIDEO_BURST |MIPI_DSI_MODE_LPM;
	
	//| MIPI_DSI_MODE_VIDEO_BURST;
	
		//MIPI_DSI_CLOCK_NON_CONTINUOUS;
		// 	   MIPI_DSI_MODE_VIDEO | MIPI_DSI_MODE_VIDEO_BURST|
		// MIPI_DSI_CLOCK_NON_CONTINUOUS;
	
	ctx->panel.prepare_prev_first = true;

	ctx->panel.backlight = visionox_vtdr6110_create_backlight(dsi);
	if (IS_ERR(ctx->panel.backlight))
		return dev_err_probe(dev, PTR_ERR(ctx->panel.backlight),
				     "Failed to create backlight\n");

	drm_panel_add(&ctx->panel);

	ret = mipi_dsi_attach(dsi);
	if (ret < 0) {
		dev_err(dev, "Failed to attach to DSI host: %d\n", ret);
		drm_panel_remove(&ctx->panel);
		return ret;
	}



	// ret = device_create_file(connector->kdev, &dev_attr_color_profile);
	ret = sysfs_create_file(&dsi->dev.kobj, &dev_attr_color_profile.attr);
	if (ret) {
		dev_err(&dsi->dev, "failed to create color_profile sysfs entry\n");
	}

	device_create_file(&dsi->dev, &dev_attr_pibrick_display_enable);
	return 0;
}

static void visionox_vtdr6110_remove(struct mipi_dsi_device *dsi)
{
	struct visionox_vtdr6110 *ctx = mipi_dsi_get_drvdata(dsi);
	int ret;

	ret = mipi_dsi_detach(dsi);
	if (ret < 0)
		dev_err(&dsi->dev, "Failed to detach from DSI host: %d\n", ret);

	drm_panel_remove(&ctx->panel);

	device_remove_file(&dsi->dev, &dev_attr_color_profile);
}

